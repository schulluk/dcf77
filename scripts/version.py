# Embeds the firmware version (git commit, "-dirty" with uncommitted
# changes) and build time, shown on the status page and logged at boot, so
# you can tell which build a board is running, e.g. after a WiFi update.
import datetime
import os
import subprocess

Import("env")  # noqa: F821, provided by PlatformIO

try:
    version = subprocess.run(
        ["git", "describe", "--always", "--dirty", "--tags"],
        cwd=env.subst("$PROJECT_DIR"), check=True, capture_output=True, text=True,
    ).stdout.strip()
except (OSError, subprocess.CalledProcessError):
    version = "unknown"
built = datetime.datetime.now().astimezone().strftime("%Y-%m-%d %H:%M %Z")

header = (
    "// Generated by scripts/version.py, do not edit.\n"
    "#pragma once\n"
    f'#define FW_VERSION "{version}"\n'
    f'#define FW_BUILT "{built}"\n'
)
gen_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
os.makedirs(gen_dir, exist_ok=True)
path = os.path.join(gen_dir, "version.h")
if not os.path.isfile(path) or open(path).read() != header:
    with open(path, "w") as f:
        f.write(header)
env.Append(CPPPATH=[gen_dir])
print(f"Firmware version: {version}, built {built}")
