# Embeds the public half of the OTA signing key into the firmware, which then
# only accepts WiFi updates signed with the private half. Runs before every
# build and stops it if the key is missing, so nobody ends up with firmware
# that can't be updated over WiFi without knowing why.
#
# Key location: ota_signing.pem in the project root, or the path in the
# OTA_SIGNING_KEY environment variable. See README, "Updates over WiFi".
import hashlib
import os
import subprocess

Import("env")  # noqa: F821, provided by PlatformIO

project_dir = env.subst("$PROJECT_DIR")
key = os.environ.get("OTA_SIGNING_KEY", os.path.join(project_dir, "ota_signing.pem"))

if not os.path.isfile(key):
    print(f"""
*** OTA signing key not found: {key}

The firmware only accepts WiFi updates signed with this key. Create it once:

    openssl ecparam -name prime256v1 -genkey -noout -out ota_signing.pem

It is gitignored. Back it up outside the repo (e.g. your password manager):
without it, the next update has to go over USB again, with a new key.
See README, "Updates over WiFi".
""")
    env.Exit(1)

pem = subprocess.run(
    ["openssl", "pkey", "-in", key, "-pubout"], check=True, capture_output=True, text=True
).stdout
der = subprocess.run(
    ["openssl", "pkey", "-pubin", "-outform", "DER"],
    input=pem.encode(), check=True, capture_output=True,
).stdout
fingerprint = hashlib.sha256(der).hexdigest()[:16]

header = (
    "// Generated by scripts/ota_signing.py, do not edit.\n"
    "#pragma once\n"
    f'#define OTA_KEY_FINGERPRINT "{fingerprint}"\n'
    "static const char OTA_PUBLIC_KEY[] =\n"
    + "".join(f'    "{line}\\n"\n' for line in pem.strip().splitlines())
    + "    ;\n"
)
gen_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
os.makedirs(gen_dir, exist_ok=True)
path = os.path.join(gen_dir, "ota_pubkey.h")
if not os.path.isfile(path) or open(path).read() != header:
    with open(path, "w") as f:
        f.write(header)
env.Append(CPPPATH=[gen_dir])
print(f"OTA signing key fingerprint: {fingerprint}")
